export function midiToNoteName(midi: number): string {
  const names = ['C', 'C#', 'D', 'Eb', 'E', 'F', 'F#', 'G', 'Ab', 'A', 'Bb', 'B'];
  const octave = Math.floor(midi / 12) - 1;
  const note = names[((midi % 12) + 12) % 12];
  return `${note}${octave}`;
}

export interface WorshipChordDef {
  label: string;
  role: string;
  midiNotes: number[];
}

export function getDiatonicWorshipChords(key: MusicalKey): WorshipChordDef[] {
  const root = 48 + KEY_TO_SEMITONE[key]; // C3-based voicing root
  // Rich open worship voicings (root + 5th in LH, add9/sus/7th in RH)
  return [
    {
      label: `${key}`,
      role: 'I',
      midiNotes: [root, root + 7, root + 12, root + 14, root + 16, root + 19],
    },
    {
      label: `${MUSICAL_KEYS[(KEY_TO_SEMITONE[key] + 9) % 12]}m7`,
      role: 'vi7',
      midiNotes: [root - 3, root + 4, root + 9, root + 12, root + 16, root + 19],
    },
    {
      label: `${MUSICAL_KEYS[(KEY_TO_SEMITONE[key] + 5) % 12]}2`,
      role: 'IV2',
      midiNotes: [root - 7, root, root + 5, root + 7, root + 12, root + 14],
    },
    {
      label: `${MUSICAL_KEYS[(KEY_TO_SEMITONE[key] + 7) % 12]}`,
      role: 'V',
      midiNotes: [root - 5, root + 2, root + 7, root + 11, root + 14, root + 19],
    },
    {
      label: `${key}/${MUSICAL_KEYS[(KEY_TO_SEMITONE[key] + 4) % 12]}`,
      role: 'I/3',
      midiNotes: [root - 8, root, root + 7, root + 12, root + 14, root + 19],
    },
    {
      label: `${MUSICAL_KEYS[(KEY_TO_SEMITONE[key] + 2) % 12]}m7`,
      role: 'ii7',
      midiNotes: [root - 10, root - 3, root + 2, root + 5, root + 12, root + 16],
    },
    {
      label: `${MUSICAL_KEYS[(KEY_TO_SEMITONE[key] + 7) % 12]}/${MUSICAL_KEYS[(KEY_TO_SEMITONE[key] + 11) % 12]}`,
      role: 'V/7',
      midiNotes: [root - 1, root + 7, root + 14, root + 19, root + 23],
    },
    {
      label: `${MUSICAL_KEYS[(KEY_TO_SEMITONE[key] + 5) % 12]}maj7`,
      role: 'IVmaj7',
      midiNotes: [root - 7, root, root + 9, root + 12, root + 16, root + 19],
    },
  ];
}

